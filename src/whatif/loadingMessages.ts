const HISTORY_LENGTH = 15;

/**
 * Cycles through LOADING_MESSAGES at random while `active`. Avoids repeating
 * anything shown in roughly the last HISTORY_LENGTH picks (falls back to
 * only avoiding the immediate previous one once the pool is smaller than
 * that window), so a long multi-batch pull doesn't cycle back to the same
 * few lines every few seconds.
 */
export function useLoadingMessage(active: boolean, intervalMs = 1800): string {
  const [message, setMessage] = useState(() => LOADING_MESSAGES[Math.floor(Math.random() * LOADING_MESSAGES.length)]);
  const recent = useRef<number[]>([]);

  useEffect(() => {
    if (!active) return;

    function pickNext() {
      const windowSize = Math.min(HISTORY_LENGTH, Math.max(0, LOADING_MESSAGES.length - 1));
      let next = Math.floor(Math.random() * LOADING_MESSAGES.length);
      let attempts = 0;
      while (recent.current.includes(next) && attempts < 20) {
        next = Math.floor(Math.random() * LOADING_MESSAGES.length);
        attempts += 1;
      }
      recent.current.push(next);
      if (recent.current.length > windowSize) recent.current.shift();
      setMessage(LOADING_MESSAGES[next]);
    }

    pickNext();
    const id = setInterval(pickNext, intervalMs);
    return () => clearInterval(id);
  }, [active, intervalMs]);

  return message;
}
